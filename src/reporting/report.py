NOT_RUN = "_Not available: this stage has not been run on real data yet._"


def _pct(x: float | None, digits: int = 1) -> str:
    return "n/a" if x is None else f"{x * 100:.{digits}f}%"


def _num(x: float | None, digits: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    if df is None or df.empty:
        return "_(empty)_"
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, row in df.iterrows():
        cells = []
        for v in row:
            cells.append(floatfmt.format(v) if isinstance(v, (float, np.floating)) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


# ----------------------------------------------------------------------------- descriptive churn tables
def churn_rate_by_group(snapshots: pd.DataFrame, min_rows: int = 30) -> pd.DataFrame:
    """Observed churn rate by simple behavioural / categorical groups (descriptive, not causal)."""
    rows: list[dict[str, Any]] = []

    def add(dim: str, series: pd.Series) -> None:
        g = snapshots.groupby(series, observed=True)["churned"].agg(rows="size", churn_rate="mean").reset_index()
        g.columns = ["group", "rows", "churn_rate"]
        for _, r in g.iterrows():
            if r["rows"] >= min_rows:
                rows.append({"dimension": dim, "group": str(r["group"]), "rows": int(r["rows"]), "churn_rate": float(r["churn_rate"])})

    if "charclass" in snapshots:
        add("class", snapshots["charclass"])
    if "race" in snapshots:
        add("race", snapshots["race"])
    add("recency", pd.cut(snapshots["days_since_last_active"], [-0.001, 1, 3, 7, 14, 1e9],
                          labels=["<=1 day", "1-3 days", "3-7 days", "7-14 days", ">14 days"]))
    add("active_days_in_window", pd.cut(snapshots["active_days"], [0, 2, 6, 13, 20, 1e9],
                                        labels=["1-2", "3-6", "7-13", "14-20", "21+"]))
    if "has_guild" in snapshots:
        add("in_guild", snapshots["has_guild"].map({0: "no guild", 1: "in a guild"}))
    add("level_band", pd.cut(snapshots["level_last"], [0, 19, 39, 59, 79, 80], labels=["1-19", "20-39", "40-59", "60-79", "80"]))
    return pd.DataFrame(rows, columns=["dimension", "group", "rows", "churn_rate"])


# ----------------------------------------------------------------------------- dataset card
def write_dataset_card(paths, cfg: dict[str, Any], profile: dict[str, Any], load_report: dict[str, Any], run_info: dict[str, Any]) -> str:
    ds = cfg["dataset"]
    cols = pd.DataFrame(profile["columns"])
    clean = profile["cleaning"]
    optional_rows = "| Optional columns (zone, race, class, guild) | " + (
        "not in this file" if not load_report.get("optional_columns_present")
        else f"present: {', '.join(load_report['optional_columns_present'])}") + " |"
    if profile.get("zones") is not None:
        optional_rows += f"\n| Zones | {profile['zones']} |"
    if profile.get("races"):
        optional_rows += f"\n| Races | {', '.join(profile['races'])} |"
    if profile.get("classes"):
        optional_rows += f"\n| Classes | {', '.join(profile['classes'])} |"
    if profile.get("share_rows_without_guild") is not None:
        optional_rows += f"\n| Share of rows with no guild | {_pct(profile['share_rows_without_guild'])} |"
    text = f"""# Dataset card (generated from the loaded file)

> Generated by `python -m src.pipeline` on {run_info.get('created_at')}. Every figure below was measured on the file that was
> actually loaded. Static provenance and licence notes are in `docs/DATASET_CARD.md`.

**Dataset:** {ds['name']}
**Kaggle page:** {ds['kaggle_url']}
**Original research source:** {ds['original_source_url']}
**Data origin recorded for this run:** `{run_info.get('data_origin')}`

## File that was loaded
| Property | Value |
|---|---|
| File name | `{load_report['file']['file_name']}` |
| Size (bytes) | {load_report['file']['file_bytes']:,} |
| SHA-256 | `{load_report['file']['sha256']}` |
| Raw header | `{load_report['raw_header']}` |
| Timestamp format used | `{load_report['timestamp_format']}` (parse rate {load_report['timestamp_parse_rate_overall']:.4%}) |

## Measured facts
| Fact | Value |
|---|---|
| Rows read | {clean['rows_read']:,} |
| Rows after cleaning | {clean['rows_after_cleaning']:,} |
| Duplicate (avatar, timestamp) rows removed | {clean['duplicate_avatar_timestamp_rows_removed']:,} |
| Rows dropped for invalid level (outside {load_report['level_range_applied']}) | {clean['dropped_invalid_level']:,} |
| Rows dropped for unusable avatar/timestamp | {clean['dropped_unusable_avatar_or_timestamp']:,} |
| Distinct avatars | {profile['avatars']:,} |
| First timestamp | {profile['date_min']} |
| Last timestamp | {profile['date_max']} |
| Span (days) | {profile['span_days']:.1f} |
| Days with at least one poll | {profile['distinct_days']} |
| Level range observed | {profile['level_min']} - {profile['level_max']} |
{optional_rows}

## Schema after cleaning
{md_table(cols)}

## Missing values in the raw file
{md_table(pd.DataFrame({'column': list(clean['missing_values_raw'].keys()), 'missing': list(clean['missing_values_raw'].values())}))}

## Preprocessing decisions
* Header names matched case-insensitively after trimming; timestamp format detected and verified over the whole file.
* Rows with unusable avatar id or timestamp, or with a level outside the configured range, are dropped and counted above.
* Missing guild is treated as "no guild"; missing race/class/zone is labelled `Unknown` (counts in `reports/evaluation/load_report.json`).
* Duplicate (avatar, timestamp) pairs are removed (an avatar cannot be observed twice at the same instant).
* Data are sorted by time; all later stages read only the cleaned table in `data/processed/`. The raw file is never modified.
"""
    paths.dataset_card.write_text(text, encoding="utf-8")
    return text


# ----------------------------------------------------------------------------- insights
def build_insights(paths) -> list[dict[str, str]]:
    """Plain-language findings composed from measured results only."""
    out: list[dict[str, str]] = []
    metrics = read_json(paths.metrics)
    definition = read_json(paths.churn_definition)
    seg = read_json(paths.segmentation_report)
    explain = read_json(paths.explain_report)
    profile = read_json(paths.dataset_profile)

    if profile:
        out.append(
            {
                "title": "Dataset scope",
                "text": f"The analysis covers {profile['avatars']:,} avatars and {profile['rows']:,} polls between "
                f"{profile['date_min'][:10]} and {profile['date_max'][:10]} ({profile['span_days']:.0f} days).",
                "evidence": "reports/evaluation/dataset_profile.json",
            }
        )
    if metrics and definition:
        sel = metrics["selected_model"]
        t = metrics["test"][sel]
        base = metrics["test"]["dummy_prior"]
        tuned = metrics["test_selected_tuned_threshold"]
        out.append(
            {
                "title": "Churn prediction performance",
                "text": (
                    f"On held-out avatars over the {len(definition['plan'].get('test_cutoffs_newest_first', [1]))} newest 28-day periods (latest cutoff {definition['plan']['test_cutoff'][:10]}), the selected model "
                    f"({sel.replace('_', ' ')}) reaches ROC-AUC {_num(t['roc_auc'])} and PR-AUC {_num(t['pr_auc'])} "
                    f"(prior-only baseline: ROC-AUC {_num(base['roc_auc'])}, PR-AUC {_num(base['pr_auc'])}; "
                    f"churn prevalence {_pct(t['prevalence'])}). At the validation-tuned threshold {tuned['threshold']:.2f}, "
                    f"precision is {_pct(tuned['precision'])} and recall {_pct(tuned['recall'])}."
                ),
                "evidence": "reports/evaluation/metrics.json",
            }
        )
        for w in metrics.get("warnings", []):
            out.append({"title": "Caveat", "text": w, "evidence": "reports/evaluation/metrics.json"})
    if explain and explain.get("top_features"):
        top = ", ".join(explain["top_features"][:5])
        out.append(
            {
                "title": "What the model relies on",
                "text": f"Most influential features ({explain['method']}): {top}. {CAUSALITY_WARNING}",
                "evidence": "reports/evaluation/explainability_report.json",
            }
        )
    if seg:
        sizes = seg["cluster_sizes"]
        total = sum(sizes.values())
        largest = max(sizes, key=lambda k: sizes[k])
        out.append(
            {
                "title": "Player segments",
                "text": (
                    f"K-Means with k={seg['chosen_k']} (silhouette {_num(seg['silhouette_final_sample'])}, seed-stability ARI "
                    f"{_num(seg.get('stability_ari_mean'))}) on {seg['avatars_clustered']:,} avatars with >= {seg['min_active_days']} active days. "
                    f"The largest segment (#{largest}) holds {_pct(sizes[largest] / total)} of clustered avatars: "
                    f"{seg['descriptors'].get(str(largest), seg['descriptors'].get(largest, ''))}."
                ),
                "evidence": "reports/evaluation/segmentation_report.json",
            }
        )
        if seg.get("silhouette_final_sample") is not None and seg["silhouette_final_sample"] < 0.25:
            out.append(
                {
                    "title": "Caveat",
                    "text": "The silhouette score is low, which means segments overlap and behaviour varies continuously. "
                    "Treat the segments as a descriptive summary rather than sharply separated player types.",
                    "evidence": "reports/evaluation/segmentation_report.json",
                }
            )
    groups = paths.churn_by_group
    if groups.is_file():
        g = pd.read_csv(groups)
        rec = g[g["dimension"] == "recency"]
        if len(rec) >= 2:
            lo, hi = rec.iloc[0], rec.iloc[-1]
            out.append(
                {
                    "title": "Recency and churn (descriptive)",
                    "text": f"Observed churn is {_pct(lo['churn_rate'])} for avatars last seen {lo['group']} before the cutoff "
                    f"versus {_pct(hi['churn_rate'])} for those last seen {hi['group']} before it.",
                    "evidence": "reports/evaluation/churn_rate_by_group.csv",
                }
            )
    return out


# ----------------------------------------------------------------------------- evaluation report
def write_evaluation_report(paths, cfg: dict[str, Any]) -> str:
    metrics = read_json(paths.metrics)
    definition = read_json(paths.churn_definition)
    seg = read_json(paths.segmentation_report)
    explain = read_json(paths.explain_report)
    run_info = read_json(paths.run_info) or {}
    profile = read_json(paths.dataset_profile)

    parts: list[str] = ["# GameSense evaluation report", ""]
    origin = run_info.get("data_origin", "unknown")
    parts.append(f"*Generated {run_info.get('created_at', 'n/a')} - data origin: `{origin}`*")
    if origin != "user_provided_file":
        parts += ["", f"> **WARNING: this report was produced from `{origin}`, NOT from the Kaggle dataset. "
                  "Do not cite these numbers as results on real data.**"]
    parts += ["", "## 1. Data", ""]
    if profile:
        parts.append(f"{profile['rows']:,} polls, {profile['avatars']:,} avatars, {profile['date_min']} to {profile['date_max']}.")
        if run_info.get("raw_file"):
            parts.append(f"\nSource file `{run_info['raw_file']['file_name']}`, SHA-256 `{run_info['raw_file']['sha256']}`.")
    else:
        parts.append(NOT_RUN)

    parts += ["", "## 2. Churn definition", ""]
    if definition:
        parts.append(definition["definition"])
        parts.append("")
        plan = definition["plan"]
        parts.append(f"* Usable data: {plan['usable_data_start'][:10]} -> {plan['usable_data_end'][:10]}")
        parts.append(f"* Test cutoffs (newest first): {', '.join(c[:10] for c in plan.get('test_cutoffs_newest_first', [plan['test_cutoff']]))}")
        parts.append(f"* Training cutoffs (newest first; the newest {definition['spec'].get('n_valid_cutoffs', 1)} are used for validation, the rest for fitting): "
                     f"{plan['train_cutoffs_newest_first'][0][:10]} back to {plan['train_cutoffs_newest_first'][-1][:10]} ({len(plan['train_cutoffs_newest_first'])} cutoffs, 28 days apart)")
        parts.append("* Training labels are fully known before the earliest test observation window begins.")
        parts.append("* Avatars are split into disjoint train / validation / test groups; the test set is also the newest period (out-of-time).")
        sets = definition["sets"]
        parts.append("")
        parts.append(md_table(pd.DataFrame([{"set": k, "rows": v["rows"], "churn rate": v["churn_rate"]} for k, v in sets.items()])))
    else:
        parts.append(NOT_RUN)

    parts += ["", "## 3. Model comparison", ""]
    if metrics:
        rows = []
        for split, key in (("validation", "validation"), ("test", "test")):
            for name, m in metrics[key].items():
                rows.append({"split": split, "model": name, "ROC-AUC": m["roc_auc"], "PR-AUC": m["pr_auc"],
                             "precision": m["precision"], "recall": m["recall"], "F1": m["f1"]})
        parts.append(md_table(pd.DataFrame(rows)))
        sel = metrics["selected_model"]
        tuned = metrics["test_selected_tuned_threshold"]
        c = tuned["confusion"]
        parts += [
            "",
            f"**Selected model:** `{sel}` ({metrics['selection_rule']}).",
            f"**Threshold:** {tuned['threshold']:.3f} ({metrics['threshold_rule']}).",
            "",
            f"Test metrics at that threshold: precision {_num(tuned['precision'])}, recall {_num(tuned['recall'])}, F1 {_num(tuned['f1'])}, "
            f"ROC-AUC {_num(tuned['roc_auc'])}, PR-AUC {_num(tuned['pr_auc'])}.",
            "",
            "**95% bootstrap intervals on the test set (resampling avatars, "
            f"{metrics['test_bootstrap_ci']['n_boot']} resamples, {metrics['test_bootstrap_ci']['n_avatars']} avatars):**",
            "",
            md_table(pd.DataFrame([{"model": n, "ROC-AUC 95% CI": "-" if v["roc_auc"] is None else f"{v['roc_auc'][0]:.3f} to {v['roc_auc'][1]:.3f}",
                                    "PR-AUC 95% CI": "-" if v["pr_auc"] is None else f"{v['pr_auc'][0]:.3f} to {v['pr_auc'][1]:.3f}",
                                    "ROC-AUC difference vs recency_only": "-" if n not in metrics["test_bootstrap_ci"]["roc_auc_difference_vs_reference"] or metrics["test_bootstrap_ci"]["roc_auc_difference_vs_reference"][n] is None
                                    else f"{metrics['test_bootstrap_ci']['roc_auc_difference_vs_reference'][n][0]:+.3f} to {metrics['test_bootstrap_ci']['roc_auc_difference_vs_reference'][n][1]:+.3f}"}
                                   for n, v in metrics["test_bootstrap_ci"]["models"].items()])),
            "",
            "Confusion matrix (test, rows = actual):",
            "",
            md_table(pd.DataFrame([["retained", c["tn"], c["fp"]], ["churned", c["fn"], c["tp"]]],
                                  columns=["actual", "predicted retained", "predicted churned"])),
            "",
            "Class imbalance is handled with class-weighted training; because accuracy is misleading when classes are unbalanced, "
            "PR-AUC, precision and recall are reported alongside ROC-AUC.",
        ]
        parts += ["", "**Warnings recorded during training**", ""] + [f"* {w}" for w in metrics.get("warnings", [])]
    else:
        parts.append(NOT_RUN)

    parts += ["", "## 4. Segmentation", ""]
    if seg:
        parts.append(f"k = {seg['chosen_k']}: {seg['k_selection_reason']}")
        parts.append(f"\nFinal silhouette (sample) {_num(seg['silhouette_final_sample'])}; mean ARI across re-fits with other seeds {_num(seg.get('stability_ari_mean'))}.")
        parts.append(f"\n{seg['avatars_clustered']:,} avatars clustered; {seg['avatars_excluded_insufficient_activity']:,} excluded for having fewer than {seg['min_active_days']} active days.\n")
        sizes = seg["cluster_sizes"]
        parts.append(md_table(pd.DataFrame([{"segment": k, "avatars": v, "description": seg["descriptors"].get(str(k), seg["descriptors"].get(k, ""))}
                                            for k, v in sizes.items()])))
    else:
        parts.append(NOT_RUN)

    parts += ["", "## 5. Explainability", ""]
    if explain:
        parts.append(f"Method: **{explain['method']}**. {explain.get('note', '')}")
        if explain.get("top_features"):
            parts.append("\nTop features: " + ", ".join(explain["top_features"][:8]) + ".")
        parts.append(f"\n> {CAUSALITY_WARNING}")
    else:
        parts.append(NOT_RUN)

    parts += [
        "",
        "## 6. Limitations",
        "",
        "See `docs/LIMITATIONS.md`. Key points: avatar is not player; one server and one faction; polling gaps and maintenance windows; "
        "left-censored tenure; churn = inactivity, not departure; results are for this dataset and period only.",
        "",
    ]
    text = "\n".join(parts)
    paths.evaluation_report.write_text(text, encoding="utf-8")
    return text
