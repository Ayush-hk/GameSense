"""Configuration loading and project path resolution."""
from __future__ import annotations

import copy
import os
from pathlib import Path
from typing import Any

import yaml

PACKAGE_ROOT = Path(__file__).resolve().parents[1]


def project_root() -> Path:
    """Project root. The GAMESENSE_ROOT environment variable overrides it (used by tests)."""
    override = os.environ.get("GAMESENSE_ROOT")
    return Path(override).resolve() if override else PACKAGE_ROOT


def _deep_update(base: dict[str, Any], updates: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(base)
    for key, value in updates.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = _deep_update(out[key], value)
        else:
            out[key] = value
    return out


def load_config(path: str | Path | None = None, overrides: dict[str, Any] | None = None) -> dict[str, Any]:
    """Load configs/config.yaml (falling back to the packaged copy) and apply overrides."""
    if path is not None:
        cfg_path = Path(path)
    else:
        local = project_root() / "configs" / "config.yaml"
        cfg_path = local if local.exists() else PACKAGE_ROOT / "configs" / "config.yaml"
    if not cfg_path.exists():
        raise FileNotFoundError(f"Config file not found: {cfg_path}")
    with open(cfg_path, "r", encoding="utf-8") as fh:
        cfg = yaml.safe_load(fh) or {}
    if overrides:
        cfg = _deep_update(cfg, overrides)
    return cfg


class Paths:
    """All filesystem locations used by the project, resolved against one root."""

    def __init__(self, cfg: dict[str, Any], root: str | Path | None = None):
        self.root = Path(root).resolve() if root else project_root()
        p = cfg["paths"]
        self.raw_dir = self.root / p["raw_dir"]
        self.processed_dir = self.root / p["processed_dir"]
        self.models_dir = self.root / p["models_dir"]
        self.preprocessors_dir = self.root / p["preprocessors_dir"]
        self.evaluation_dir = self.root / p["evaluation_dir"]
        self.figures_dir = self.root / p["figures_dir"]
        self.docs_dir = self.root / p.get("docs_dir", "docs")

        # processed data (pickled pandas tables: local cache files generated by the pipeline,
        # never exchanged between machines -> do not load .pkl files from untrusted sources)
        self.events_table = self.processed_dir / "events.pkl"
        self.profiles_table = self.processed_dir / "avatar_profiles.pkl"
        self.churn_snapshots = self.processed_dir / "churn_snapshots.pkl"
        self.daily_activity = self.processed_dir / "daily_activity.csv"
        self.hourly_activity = self.processed_dir / "hourly_activity.csv"

        # model artifacts
        self.churn_model = self.models_dir / "churn_model.joblib"
        self.churn_meta = self.models_dir / "churn_model_meta.json"
        self.kmeans_model = self.models_dir / "segmentation_kmeans.joblib"
        self.seg_preprocessor = self.preprocessors_dir / "segmentation_preprocessor.joblib"

        # reports
        self.run_info = self.evaluation_dir / "run_info.json"
        self.pipeline_status = self.evaluation_dir / "pipeline_status.json"
        self.dataset_profile = self.evaluation_dir / "dataset_profile.json"
        self.load_report = self.evaluation_dir / "load_report.json"
        self.dataset_card = self.evaluation_dir / "dataset_card_generated.md"
        self.segmentation_report = self.evaluation_dir / "segmentation_report.json"
        self.cluster_selection = self.evaluation_dir / "cluster_selection.csv"
        self.cluster_profiles = self.evaluation_dir / "cluster_profiles.csv"
        self.churn_definition = self.evaluation_dir / "churn_definition.json"
        self.metrics = self.evaluation_dir / "metrics.json"
        self.model_comparison = self.evaluation_dir / "model_comparison.csv"
        self.confusion_matrix = self.evaluation_dir / "confusion_matrix.csv"
        self.classification_report = self.evaluation_dir / "classification_report.txt"
        self.roc_curve = self.evaluation_dir / "roc_curve.csv"
        self.pr_curve = self.evaluation_dir / "pr_curve.csv"
        self.shap_global = self.evaluation_dir / "shap_global_importance.csv"
        self.shap_sample = self.evaluation_dir / "shap_sample.csv"
        self.permutation_importance = self.evaluation_dir / "permutation_importance.csv"
        self.explain_report = self.evaluation_dir / "explainability_report.json"
        self.churn_by_group = self.evaluation_dir / "churn_rate_by_group.csv"
        self.insights = self.evaluation_dir / "insights.json"
        self.evaluation_report = self.evaluation_dir / "evaluation_report.md"

    def ensure(self) -> "Paths":
        for d in (
            self.raw_dir,
            self.processed_dir,
            self.models_dir,
            self.preprocessors_dir,
            self.evaluation_dir,
            self.figures_dir,
        ):
            d.mkdir(parents=True, exist_ok=True)
        return self


def get_paths(cfg: dict[str, Any], root: str | Path | None = None) -> Paths:
    return Paths(cfg, root)
